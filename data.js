function createEvent(id, name, shortName, entries) {
  const booths = entries.map((entry, index) => {
    const row = Math.floor(index / 8);
    const position = index % 8;
    const column = Math.floor(position / 2);
    const x = layouts.columns[column] + (position % 2) * 82;
    const y = layouts.rows[row];
    const code = `${String.fromCharCode(65 + row)}${String(position + 1).padStart(2, '0')}`;
    const [boothName, category, description, popularity, novelty, tags] = entry;
    return {
      id: `${id}-${code.toLowerCase()}`,
      code,
      name: boothName,
      category,
      description,
      popularity,
      novelty,
      dwellMinutes: category === '체험' ? 12 : category === '원두' ? 7 : 5,
      x,
      y,
      width: 74,
      height: 92,
      access: { x: x + 37, y: layouts.horizontalAisles[row + 1] },
      tags,
    };
  });
  return {
    id,
    name,
    shortName,
    venue: '샘플 전시장 · A홀',
    description: '기능 체험을 위한 가상 부스와 배치입니다. 실제 행사 정보가 아닙니다.',
    isSample: true,
    map: { width: 1000, height: 740, metresPerUnit: 0.5, ...layouts },
    categories: [...new Set(booths.map((booth) => booth.category))],
    entrances: entrances.map((entrance) => ({ ...entrance, point: { ...entrance.point }, access: { ...entrance.access } })),
    booths,
  };
}

